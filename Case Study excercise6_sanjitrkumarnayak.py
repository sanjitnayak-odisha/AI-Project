# Mini-RAG simulation
sop_documents = [

    """
    Acknowledgment:
    Every grievance received through the portal
    should be acknowledged in the system.
    Include the grievance reference number when available.
    """,

    """
    Initial Examination:
    The receiving office should examine the subject
    and identify the department competent to handle the matter.
    """,

    """
    Urgent Grievances:
    Complaints involving immediate threats to life,
    public safety or essential services should be
    flagged for prompt human review.
    """,

    """
    Privacy:
    Aadhaar numbers, bank account details, mobile
    numbers and addresses must be protected.
    Access should be restricted to authorized personnel.
    """
]

# Create the retrieval system
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

vectorizer = TfidfVectorizer(stop_words="english")

sop_vectors = vectorizer.fit_transform(sop_documents)


def retrieve_sop(query):

    query_vector = vectorizer.transform([query])

    similarity = cosine_similarity(
        query_vector,
        sop_vectors
    )

    best_index = similarity.argmax()

    return sop_documents[best_index]


citizen_query = """
How should the department acknowledge a grievance
and handle urgent complaints?
"""

result = retrieve_sop(citizen_query)

print("Retrieved SOP Information:")
print(result)

# create a simple grounded answer
def generate_rag_response(query):

    context = retrieve_sop(query)

    response = f"""
    Citizen Query:
    {query}

    Retrieved Government SOP:
    {context}

    Answer:
    Based only on the provided SOP, the concerned
    office should follow the procedures described
    in the retrieved guideline. Any matter involving
    immediate safety concerns should be referred
    for prompt human review.
    """

    return response


print(generate_rag_response(citizen_query))

