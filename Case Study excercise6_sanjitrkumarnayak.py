#  PII masking using Python Regex
def mask_pii(text):

    # Mask Aadhaar-like 12 digit number
    text = re.sub(
        r'\b\d{4}[ -]?\d{4}[ -]?\d{4}\b',
        '[AADHAAR MASKED]',
        text
    )

    # Mask Indian mobile number
    text = re.sub(
        r'(?<!\d)(?:\+91[- ]?|0)?[6-9]\d{9}(?!\d)',
        '[MOBILE MASKED]',
        text
    )

    # Mask email address
    text = re.sub(
        r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b',
        '[EMAIL MASKED]',
        text
    )

    return text


